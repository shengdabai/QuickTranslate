import { test } from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { compareVersions, parseCargoLock } from "./check-tauri-versions.mjs";

const SCRIPT = join(dirname(fileURLToPath(import.meta.url)), "check-tauri-versions.mjs");

function cargoLock(packages) {
  const body = Object.entries(packages)
    .map(([name, version]) => `[[package]]\nname = "${name}"\nversion = "${version}"\nsource = "registry+https://github.com/rust-lang/crates.io-index"\n`)
    .join("\n");
  return `# This file is automatically @generated by Cargo.\nversion = 4\n\n${body}`;
}

function fakeRepo(crates, npmPackages) {
  const root = mkdtempSync(join(tmpdir(), "check-tauri-versions-"));
  mkdirSync(join(root, "src-tauri"));
  writeFileSync(join(root, "src-tauri", "Cargo.lock"), cargoLock(crates));
  for (const [name, version] of Object.entries(npmPackages)) {
    const dir = join(root, "node_modules", ...name.split("/"));
    mkdirSync(dir, { recursive: true });
    writeFileSync(join(dir, "package.json"), JSON.stringify({ name, version }));
  }
  return root;
}

function runScript(root) {
  return spawnSync(process.execPath, [SCRIPT, root], { encoding: "utf8" });
}

test("parseCargoLock reads every [[package]] name/version", () => {
  const crates = parseCargoLock(cargoLock({ tauri: "2.12.4", "tauri-plugin-store": "2.4.2", serde: "1.0.228" }));
  assert.deepEqual(crates.get("tauri"), ["2.12.4"]);
  assert.deepEqual(crates.get("tauri-plugin-store"), ["2.4.2"]);
  assert.deepEqual(crates.get("serde"), ["1.0.228"]);
});

test("flags tauri crate vs @tauri-apps/api on a different minor (the tauri build failure)", () => {
  const crates = parseCargoLock(cargoLock({ tauri: "2.12.4" }));
  const { mismatches, errors } = compareVersions(crates, { "@tauri-apps/api": "2.11.1" });
  assert.deepEqual(errors, []);
  assert.equal(mismatches.length, 1);
  assert.equal(mismatches[0].crate, "tauri");
});

test("accepts patch-level differences", () => {
  const crates = parseCargoLock(cargoLock({ tauri: "2.12.4", "tauri-plugin-opener": "2.5.3" }));
  const result = compareVersions(crates, { "@tauri-apps/api": "2.12.0", "@tauri-apps/plugin-opener": "2.5.5" });
  assert.deepEqual(result.mismatches, []);
  assert.deepEqual(result.errors, []);
  assert.equal(result.checked.length, 2);
});

test("flags plugin crate vs @tauri-apps/plugin-* mismatches", () => {
  const crates = parseCargoLock(cargoLock({ tauri: "2.12.4", "tauri-plugin-opener": "2.5.3" }));
  const { mismatches } = compareVersions(crates, { "@tauri-apps/api": "2.12.4", "@tauri-apps/plugin-opener": "2.7.2" });
  assert.deepEqual(mismatches.map((m) => m.crate), ["tauri-plugin-opener"]);
});

test("ignores the tauri-plugin helper crate and plugins without JS bindings", () => {
  const crates = parseCargoLock(cargoLock({ tauri: "2.12.4", "tauri-plugin": "2.5.3", "tauri-plugin-log": "2.0.0" }));
  const result = compareVersions(crates, { "@tauri-apps/api": "2.12.4", "@tauri-apps/plugin-log": undefined });
  assert.deepEqual(result.mismatches, []);
  assert.deepEqual(result.errors, []);
  assert.deepEqual(result.checked.map((c) => c.crate), ["tauri"]);
});

test("errors when @tauri-apps/api is not installed", () => {
  const crates = parseCargoLock(cargoLock({ tauri: "2.12.4" }));
  assert.equal(compareVersions(crates, {}).errors.length, 1);
});

test("CLI exits 1 on mismatch and 0 when aligned", () => {
  const bad = fakeRepo({ tauri: "2.12.4" }, { "@tauri-apps/api": "2.11.1" });
  const good = fakeRepo({ tauri: "2.12.4" }, { "@tauri-apps/api": "2.12.4" });
  try {
    const badRun = runScript(bad);
    assert.equal(badRun.status, 1, badRun.stdout + badRun.stderr);
    assert.match(badRun.stdout, /MISMATCH\s+tauri \(v2\.12\.4\) : @tauri-apps\/api \(v2\.11\.1\)/);

    const goodRun = runScript(good);
    assert.equal(goodRun.status, 0, goodRun.stdout + goodRun.stderr);
  } finally {
    rmSync(bad, { recursive: true, force: true });
    rmSync(good, { recursive: true, force: true });
  }
});
